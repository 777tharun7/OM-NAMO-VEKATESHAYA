async function loadAppData() {
  try {
    const headers = {
      'Content-Type': 'application/json'
    };
    if (currentApiKey) {
      headers['x-api-key'] = currentApiKey;
    }

    const apiUrl = '/api/app-data';
    const response = await fetch(apiUrl, { headers });
    if (!response.ok) {
      throw new Error('API unavailable');
    }

    const payload = await response.json();
    if (payload.statesData) {
      statesData = payload.statesData;
    }
    if (payload.analytics) {
      apiStatusText.textContent = `API connected • ${payload.analytics.status}`;
    } else {
      apiStatusText.textContent = 'API connected';
    }
    renderState(stateSelect.value || 'ap');
  } catch (error) {
    apiStatusText.textContent = 'API key required or backend unavailable';
    renderState(stateSelect.value || 'ap');
  }
}

