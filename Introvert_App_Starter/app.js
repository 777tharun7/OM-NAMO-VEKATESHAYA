function loadStoredState() {
  try {
    storedUsers = JSON.parse(localStorage.getItem(STORAGE_KEYS.users) || '[]');
    dashboardEntries = JSON.parse(localStorage.getItem(STORAGE_KEYS.entries) || '[]');
    currentUser = JSON.parse(localStorage.getItem(STORAGE_KEYS.currentUser) || 'null');
  } catch (error) {
    storedUsers = [];
    dashboardEntries = [];
    currentUser = null;
  }
}

